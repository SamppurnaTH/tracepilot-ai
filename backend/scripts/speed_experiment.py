"""Speed experiment: does a change make investigations faster without losing verified fixes?

Runs every variant on the same scenarios, interleaved round-robin so a slow spell at the model API hits
all variants alike. Each observation is appended to eval/speed/observations.jsonl as it finishes;
`summarize` rebuilds eval/speed/RESULTS.md from those observations only.

    python backend/scripts/speed_experiment.py run --runs 2 --parallel 3
    python backend/scripts/speed_experiment.py summarize
"""

import argparse
import json
import statistics
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.agent import Investigation  # noqa: E402
from app.scenarios import SCENARIOS  # noqa: E402

OUT = ROOT / "eval" / "speed"
OBSERVATIONS = OUT / "observations.jsonl"
SCENARIO_IDS = ["orders", "notes", "billing", "inventory"]
DECISION = (
    "Keep the current behaviour. Both speed-ups cut the median time by about 15%, but cost reviewer approvals: "
    "on Billing, whose hidden trap (an empty invoice) no test covers, the patches drew concerns in 2 of 2 no-self-test "
    "runs and 1 of 2 low-effort runs, against 0 of 2 at baseline. Eight runs per variant is a small sample, but "
    "TracePilot's promise is proof beyond green tests, so speed doesn't buy back a weaker fix."
)

# name -> (what changes, how to apply it to one investigation)
VARIANTS = {
    "baseline": ("Current behaviour", lambda inv: None),
    "no_self_test": (
        "Fix phase: the model is told the harness runs the tests, so it needn't run them itself",
        lambda inv: setattr(inv, "fix_closing", "The harness runs the full test suite after you reply, so do not run the tests yourself. Reply with one short sentence."),
    ),
    "low_effort": ("Reasoning effort set to low", lambda inv: setattr(inv, "reasoning", {"summary": "auto", "effort": "low"})),
}


def one(job: tuple[str, str, int]) -> dict:
    variant, scenario, rep = job
    events: list[dict] = []
    inv = Investigation.from_scenario(SCENARIOS[scenario], on_event=events.append)
    VARIANTS[variant][1](inv)
    row = {"variant": variant, "scenario": scenario, "rep": rep, "at": time.strftime("%Y-%m-%dT%H:%M:%S")}
    try:
        r = inv.run()
        usage, timing = r["usage"], r.get("timing", {})
        row |= {
            "outcome": r.get("outcome"),
            "verified": bool(r["verification"].get("verified")),
            "review": (r.get("second_opinion") or {}).get("verdict"),
            "duration_s": r["duration_s"],
            "model_s": timing.get("model_s"),
            "tools_s": timing.get("tools_s"),
            "verify_s": timing.get("verify_s"),
            "review_s": timing.get("review_s"),
            "by_phase": timing.get("by_phase"),
            "tokens": usage["input_tokens"] + usage["output_tokens"],
            "model_calls": usage["model_calls"],
            "error": None,
        }
    except Exception as exc:  # a crash is an observation too, never silently retried
        row |= {"outcome": "error", "verified": False, "error": f"{type(exc).__name__}: {exc}"[:300]}
    with OBSERVATIONS.open("a", encoding="utf-8") as f:
        f.write(json.dumps(row) + "\n")
    print(f"{variant:13} {scenario:10} #{rep}  {row.get('outcome')}  {row.get('duration_s')} s  {row.get('tokens')} tokens", flush=True)
    return row


def run(runs: int, parallel: int, variants: list[str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    jobs = [(v, s, rep) for rep in range(1, runs + 1) for s in SCENARIO_IDS for v in variants]
    with ThreadPoolExecutor(max_workers=parallel) as pool:
        list(pool.map(one, jobs))
    summarize()


def summarize() -> None:
    rows = [json.loads(line) for line in OBSERVATIONS.read_text(encoding="utf-8").splitlines() if line.strip()]
    out = [
        "# Speed experiment",
        "",
        "Generated by `backend/scripts/speed_experiment.py` from `observations.jsonl`. Variants were interleaved "
        "round-robin on the same scenarios, in the Docker sandbox. Small samples: medians, not significance tests.",
        "",
        "Tests verifying a fix is not enough: a patch can pass every test and still be wrong, which is what the "
        "independent reviewer checks. A speed-up counts only if reviewer approvals hold too.",
        "",
        "| Variant | What changes | Runs | Tests verified | Reviewer approved | Median time | Median model wait | Median tokens | Median model calls |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, (what, _) in VARIANTS.items():
        mine = [r for r in rows if r["variant"] == name]
        if not mine:
            continue
        done = [r for r in mine if r.get("duration_s") is not None]
        med = lambda key: statistics.median(r[key] for r in done) if done else float("nan")  # noqa: E731
        out.append(
            f"| {name} | {what} | {len(mine)} | {sum(r['verified'] for r in mine)}/{len(mine)} | "
            f"{sum(r.get('review') == 'approve' for r in mine)}/{len(mine)} | {med('duration_s'):.0f} s | "
            f"{med('model_s'):.0f} s | {med('tokens'):,.0f} | {med('model_calls'):.0f} |"
        )
    out += ["", "## Per scenario (median seconds)", "", "| Scenario | " + " | ".join(VARIANTS) + " |", "|---|" + "---|" * len(VARIANTS)]
    for s in SCENARIO_IDS:
        cells = []
        for v in VARIANTS:
            times = [r["duration_s"] for r in rows if r["variant"] == v and r["scenario"] == s and r.get("duration_s") is not None]
            cells.append(f"{statistics.median(times):.0f} ({len(times)})" if times else "—")
        out.append(f"| {s} | " + " | ".join(cells) + " |")
    failures = [r for r in rows if not r["verified"] or r.get("review") != "approve"]
    if failures:
        out += ["", "## Runs not verified or not approved by the reviewer", ""]
        out += [
            f"- {r['variant']} / {r['scenario']} #{r['rep']}: {r.get('outcome')}, reviewer {r.get('review')}{' — ' + r['error'] if r.get('error') else ''}"
            for r in failures
        ]
    out += ["", "## Decision", "", DECISION]
    (OUT / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--runs", type=int, default=2)
    r.add_argument("--parallel", type=int, default=3)
    r.add_argument("--variants", nargs="*", default=list(VARIANTS), choices=list(VARIANTS))
    sub.add_parser("summarize")
    args = parser.parse_args()
    run(args.runs, args.parallel, args.variants) if args.cmd == "run" else summarize()
