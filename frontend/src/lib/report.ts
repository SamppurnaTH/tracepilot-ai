// Hand-off documents built from a finished run, in the browser, at no token cost.

import { formatTally, needsReview, shortTest, timeParts, type RunState, type ScenarioSummary } from "./run";
import { minutes } from "./useData";

const REVIEW_LABEL: Record<string, string> = { approve: "approved", concerns: "raised concerns", reject: "rejected the fix", unavailable: "unavailable" };

export function patchScope(diff: string): string {
  const lines = diff.split("\n");
  return `${lines.filter((l) => l.startsWith("+++ b/")).length} files · +${lines.filter((l) => l.startsWith("+") && !l.startsWith("+++")).length} / −${lines.filter((l) => l.startsWith("-") && !l.startsWith("---")).length} lines (tests included). Size is descriptive, not proof of minimality.`;
}

function statusLine(state: RunState): string {
  if (state.report?.outcome === "no_code_change") return "No code change needed: the root cause is outside the code";
  const v = state.verification;
  const tests = v ? `tests ${formatTally(v.before)} → ${formatTally(v.after)}, ${v.regressions.length} regressions` : "no test run";
  const review = state.secondOpinion ? `; independent review ${REVIEW_LABEL[state.secondOpinion.verdict] ?? state.secondOpinion.verdict}` : "";
  return `${v?.verified && needsReview(state) ? "Tests verified; review required" : v?.verified ? "Fix verified" : "Not verified"} (${tests})${review}`;
}

/** Ticket text without the sandbox test credentials, which only the agent needs. */
export function publicTicket(incident: string): string {
  return incident
    .split("\n")
    .filter((line) => !/test credentials/i.test(line))
    .join("\n")
    .trim();
}

export function markdownReport(scenario: ScenarioSummary, state: RunState): string {
  const r = state.report;
  const out = [`# Incident report: ${scenario.title}`, "", `**Service:** \`${scenario.service}\`  `, `**Status:** ${statusLine(state)}`, ""];
  out.push("## Incident", "", publicTicket(scenario.incident), "");
  if (r?.findings.summary) out.push("## Summary", "", r.findings.summary, "");
  (r?.findings.issues ?? []).forEach((issue, i) => {
    out.push(`## ${i + 1}. ${issue.title}`, "", `**Severity:** ${issue.severity} · **Category:** ${issue.category}`, "", `**Root cause:** ${issue.root_cause}`, "");
    if (issue.evidence.length) out.push("**Evidence:**", ...issue.evidence.map((e) => `- ${e}`), "");
    out.push(`**Fix:** ${issue.fix}`, "");
  });
  if (state.diff) out.push("## Patch", "", "```diff", state.diff.trimEnd(), "```", "");
  if (state.diff) out.push("## Patch scope", "", patchScope(state.diff), "");
  out.push("## Verification scope", "", r?.verification_scope ?? "Recorded tests only; untested production behavior is not verified.", "");
  if (r?.excluded_tests?.length) out.push("Excluded infrastructure test classes: " + r.excluded_tests.join(", "), "");
  const v = state.verification;
  if (v) {
    out.push("## Verification", "", `Before: ${formatTally(v.before)}. After: ${formatTally(v.after)}.`, "");
    v.fixed.forEach((t) => out.push(`- fixed: \`${t}\``));
    v.regressions.forEach((t) => out.push(`- regression: \`${t}\``));
    v.still_failing.forEach((t) => out.push(`- still failing: \`${t}\``));
    out.push("");
  }
  const o = state.secondOpinion;
  if (o && o.verdict !== "unavailable") {
    out.push("## Independent review", "", `${o.model ?? "Reviewer"}: **${o.verdict}** (${o.confidence} confidence). ${o.summary ?? ""}`, "");
    (o.risks ?? []).forEach((risk) => out.push(`- ${risk}`));
    out.push("");
  }
  if (r) {
    const parts = timeParts(r.timing).map(([label, sec]) => `${label} ${minutes(sec)}`);
    out.push("## Time", "", `${minutes(r.duration_s)} in total${parts.length ? `: ${parts.join(", ")}` : ""}.`, "");
  }
  out.push("---", `Generated by TracePilot AI · investigated by ${r?.model ?? state.model ?? "Muse Spark"}${o?.model ? `, reviewed by ${o.model}` : ""}`);
  return out.join("\n");
}

export function prDescription(scenario: ScenarioSummary, state: RunState): string {
  const issues = state.report?.findings.issues ?? [];
  const title = issues.length ? `Fix: ${issues.map((i) => i.title).join("; ")}` : `Fix ${scenario.service} incident`;
  const out = [title, "", "## What was wrong", ""];
  if (needsReview(state)) out.splice(2, 0, "**Review required:** resolve the reviewer's objections before applying or merging this patch.", "");
  issues.forEach((i) => out.push(`- **${i.title}** (${i.severity} ${i.category}): ${i.root_cause}`));
  out.push("", "## What changed", "");
  issues.forEach((i) => out.push(`- ${i.fix}`));
  const v = state.verification;
  if (v) {
    out.push("", "## How it was verified", "", `- Test suite: ${formatTally(v.before)} before, ${formatTally(v.after)} after, ${v.regressions.length} regressions.`);
    v.fixed.forEach((t) => out.push(`- Now passing: ${shortTest(t)}`));
  }
  const o = state.secondOpinion;
  if (o && o.verdict !== "unavailable") out.push(`- Independent review (${o.model}): ${o.verdict}, ${o.confidence} confidence.`);
  out.push("", "_Investigated, patched and verified in a sandbox by TracePilot AI._");
  return out.join("\n");
}

export function downloadText(filename: string, text: string, type = "text/markdown"): void {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = Object.assign(document.createElement("a"), { href: url, download: filename });
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
